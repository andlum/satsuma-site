// Draws the static part of the satsuma tree (ground, trunk, branches, canopy)
// and writes it to src/_includes/tree-art.njk, which tree.njk includes.
//
//   node scripts/draw-tree.js
//
// The drawing is cel-shaded: every mass is a few flat tones with crisp edges,
// lit from the upper left. The canopy is nine clumps, each a dark blob with a
// lighter lobe on its lit side and a ring of leaves radiating from its centre.
// Run it again only to change the drawing; the output is committed.
const fs = require("fs");
const path = require("path");

// Seeded, so a rerun reproduces the same tree.
let seed = 20261111;
const rand = () => {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 4294967296;
};
const between = (a, b) => a + (b - a) * rand();
const n1 = (v) => Math.round(v * 10) / 10;

// Clumps, drawn top to bottom so each one's lit crown overlaps the shadowed
// underside of the clump above it.
const CLUMPS = [
  [200, 150, 62], [130, 195, 58], [270, 195, 58], [196, 214, 46],
  [160, 240, 55], [245, 240, 55], [105, 265, 52], [295, 265, 52], [200, 295, 60],
];
const LIGHT = [-0.6, -0.8];
const TONES = ["dark", "deep", "mid", "light", "hi"];

const out = [];
let order = 0; // growth order, read by the .grow animation as --i

out.push(`{#- Generated by scripts/draw-tree.js. Edit that, not this. -#}`);
out.push(`<defs>
  <g id="lf"><path d="M0 0 C7 -5 8.5 -14 0 -22 C-8.5 -14 -7 -5 0 0Z"/><path class="half" d="M0 0 C7 -5 8.5 -14 0 -22Z"/><path class="vein" d="M0 -3 L0 -17"/></g>
  <g id="tuft"><path d="M0 0 C-3 -5 -4 -11 -2 -17 C0 -11 1 -5 0 0Z"/><path d="M0 0 C3 -4 7 -8 6 -15 C4 -9 2 -5 0 0Z"/><path class="half" d="M0 0 C-4 -3 -8 -5 -11 -10 C-6 -7 -3 -4 0 0Z"/></g>
  <g id="daisy"><circle cy="-2.6" r="2.1"/><circle cx="2.5" cy="-.8" r="2.1"/><circle cx="1.5" cy="2.1" r="2.1"/><circle cx="-1.5" cy="2.1" r="2.1"/><circle cx="-2.5" cy="-.8" r="2.1"/><circle class="eye" r="1.3"/></g>
</defs>`);

// Ground: a grassy mound in two bands, the tree's shadow, tufts and daisies.
out.push(`<g class="land">
  <path class="mound" d="M30 460 C80 444 150 441 200 441 C250 441 320 444 370 460 C320 468 250 471 200 471 C150 471 80 468 30 460Z"/>
  <path class="mound-band" d="M30 460 C80 463 150 465 200 465 C250 465 320 463 370 460 C320 468 250 471 200 471 C150 471 80 468 30 460Z"/>
  <path class="mound-lit" d="M70 451 C110 445 160 443.500 200 443.500 C226 443.500 250 444 270 445.500 C240 445 150 446 70 451Z"/>
  <ellipse class="cast" cx="204" cy="453" rx="104" ry="6.500"/>
</g>`);
const tufts = [[84, 456, 0.8], [118, 452, 1], [150, 450, 0.75], [246, 450, 0.85], [268, 453, 1.05], [318, 457, 0.8], [176, 462, 0.7], [232, 463, 0.75]];
tufts.forEach(([x, y, s], i) => {
  out.push(`<g transform="translate(${x} ${y}) scale(${i % 2 ? -s : s} ${s})"><use href="#tuft" class="tuft${i % 3 === 0 ? " deep" : ""}"/></g>`);
});
[[102, 455, 0.9], [296, 452, 1], [226, 458, 0.8]].forEach(([x, y, s]) => {
  out.push(`<g transform="translate(${x} ${y}) scale(${s})"><use href="#daisy" class="daisy"/></g>`);
});

// Branches: tapered limbs from the top of the trunk into the clumps. They sit
// inside .crown so they lean with the canopy.
out.push(`<g class="crown">`);
const limb = (x0, y0, x1, y1, w0, w1, bend) => {
  const dx = x1 - x0, dy = y1 - y0, len = Math.hypot(dx, dy);
  const nx = -dy / len, ny = dx / len;
  const mx = (x0 + x1) / 2 + nx * bend, my = (y0 + y1) / 2 + ny * bend;
  const p = (x, y, w, s) => `${n1(x + nx * w * s)} ${n1(y + ny * w * s)}`;
  return `M${p(x0, y0, w0, 1)} Q${p(mx, my, (w0 + w1) / 2, 1)} ${p(x1, y1, w1, 1)} L${p(x1, y1, w1, -1)} Q${p(mx, my, (w0 + w1) / 2, -1)} ${p(x0, y0, w0, -1)}Z`;
};
const LIMBS = [
  [198, 356, 112, 270, 6, 1.6, 10], [202, 356, 296, 266, 6, 1.6, -10],
  [197, 354, 168, 206, 5.5, 1.4, 8], [203, 354, 252, 196, 5.5, 1.4, -8],
  [204, 358, 302, 310, 4.5, 1.4, 12], [196, 358, 108, 318, 4.5, 1.4, -12],
  [132, 290, 96, 214, 3, 1, 6], [276, 288, 304, 212, 3, 1, -6],
];
LIMBS.forEach(([x0, y0, x1, y1, w0, w1, bend], i) => {
  out.push(`<path class="branch" style="--i:${i};transform-origin:${x0}px ${y0}px" d="${limb(x0, y0, x1, y1, w0, w1, bend)}"/>`);
});

// Canopy outline: every clump once, slightly large, in the line colour. The
// fills drawn after it leave a rim around the whole silhouette.
CLUMPS.forEach(([x, y, r], i) => {
  out.push(`<circle class="blob rim" cx="${x}" cy="${y}" r="${r + 3}" style="transform-origin:${x}px ${n1(y + r * 0.7)}px;--i:${i}"/>`);
});

const inside = (px, py, [x, y, r], pad) => Math.hypot(px - x, py - y) < r - pad;
const lightAt = (x, y, ux, uy) =>
  0.5 + 0.55 * (ux * LIGHT[0] + uy * LIGHT[1]) - 0.22 * ((x - 200) / 150) - 0.25 * ((y - 220) / 135) + between(-0.14, 0.14);
// Tone 4 (hi) is kept for the few leaves facing the light head on.
const tone = (l, lift) => {
  const t = Math.max(0, Math.min(3, Math.floor(l * 3.7) + lift));
  return TONES[l > 1.02 ? 4 : t];
};
// A lobe with a bumpy edge: one disc and a few smaller ones around its rim.
const lobe = (cls, x, y, r, style) => {
  out.push(`<g class="blob ${cls}" style="${style}"><circle cx="${n1(x)}" cy="${n1(y)}" r="${n1(r)}"/>`);
  const start = between(0, 60);
  for (let a = start; a < start + 360; a += 60) {
    const rad = (a * Math.PI) / 180;
    out.push(`<circle cx="${n1(x + Math.cos(rad) * r * 0.78)}" cy="${n1(y + Math.sin(rad) * r * 0.78)}" r="${n1(r * between(0.3, 0.42))}"/>`);
  }
  out.push(`</g>`);
};

let leaves = 0;
const leaf = (x, y, rot, scale, cls) => {
  leaves++;
  out.push(`<g transform="translate(${n1(x)} ${n1(y)}) rotate(${n1(rot)}) scale(${n1(scale)})"><use href="#lf" class="leaf ${cls}" style="--i:${order++}"/></g>`);
};

CLUMPS.forEach((c, ci) => {
  const [cx, cy, r] = c;
  const later = CLUMPS.slice(ci + 1);
  const origin = `transform-origin:${cx}px ${n1(cy + r * 0.7)}px;--i:${order}`;
  const lit = 0.5 - 0.22 * ((cx - 200) / 150) - 0.25 * ((cy - 220) / 135);
  out.push(`<circle class="blob dark" cx="${cx}" cy="${cy}" r="${r}" style="${origin}"/>`);
  lobe("deep", cx - r * 0.12, cy - r * 0.15, r * 0.7, origin);
  if (lit > 0.42) lobe("mid", cx - r * 0.28, cy - r * 0.34, r * 0.4, origin);

  // Rim leaves: around the edge, pointing out and drooping a little. Skipped
  // where a later clump will cover them anyway.
  for (let a = between(0, 16); a < 360; a += between(13, 19)) {
    const rad = (a * Math.PI) / 180;
    const ux = Math.cos(rad), uy = Math.sin(rad);
    if (later.some((o) => inside(cx + ux * (r + 6), cy + uy * (r + 6), o, 10))) continue;
    const droop = ux * 16 * (uy > -0.3 ? 1 : 0.3); // tips sag away from the top
    const rot = a + 90 + droop + between(-26, 26);
    leaf(cx + ux * (r - 7), cy + uy * (r - 7), rot, between(1.35, 1.85), tone(lightAt(cx, cy, ux, uy), 0));
  }
  // Inner leaves: a loose second ring and a few on the face of the clump, one
  // tone lighter than the blob beneath so they read.
  for (let k = 0; k < 14; k++) {
    const a = k < 10 ? k * 36 + between(-12, 12) : between(0, 360), rad = (a * Math.PI) / 180;
    const d = (k < 10 ? between(0.48, 0.66) : between(0.1, 0.3)) * r;
    const ux = Math.cos(rad), uy = Math.sin(rad);
    const x = cx + ux * d, y = cy + uy * d;
    if (later.some((o) => inside(x, y, o, 6))) continue;
    leaf(x, y, a + 90 + between(-40, 40), between(1.25, 1.7), tone(lightAt(cx, cy, ux * (d / r), uy * (d / r)), 1));
  }
});
out.push(`</g>`);

// Trunk: drawn over the branch roots. Flared foot, a hard shadow down the
// right side, a highlight on the left, a few bark nicks.
out.push(`<g class="bole">
  <path class="trunk" d="M176 456 C185 446 189 424 190.500 398 C191.500 380 191 366 189 351 C194 345 206 345 211 351 C209 366 208.500 380 209.500 398 C211 424 215 446 224 456 C216 452.500 208 452.500 200 456 C192 452.500 184 452.500 176 456Z"/>
  <path class="trunk-shade" d="M203 347 C203 380 205 424 213 453 C217 453.500 221 454.500 224 456 C215 446 211 424 209.500 398 C208.500 380 209 366 211 351 C209 348.500 206 347.200 203 347Z"/>
  <path class="trunk-lit" d="M194.500 362 C195.500 386 195 414 190.500 438"/>
  <path class="bark" d="M199 372 l3 5 M197 404 l3.500 4 M203 424 l-3 5 M196 388 l-2 3"/>
  <path class="trunk-line" d="M176 456 C185 446 189 424 190.500 398 C191.500 380 191 366 189 351 M211 351 C209 366 208.500 380 209.500 398 C211 424 215 446 224 456 C216 452.500 208 452.500 200 456 C192 452.500 184 452.500 176 456"/>
</g>`);

const file = path.join(__dirname, "..", "src", "_includes", "tree-art.njk");
fs.writeFileSync(file, out.join("\n").replace(/(\d)\.500/g, "$1.5") + "\n");
console.log(`wrote ${path.relative(process.cwd(), file)}: ${leaves} leaves`);
